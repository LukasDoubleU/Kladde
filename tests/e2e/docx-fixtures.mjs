// Word documents for the e2e tests, generated at test time with the `docx` package (deflated zips, no personal
// metadata: the author is a fixed test name). Nothing here is saved by Word, and nothing is committed as a binary.
import {
  BookmarkEnd,
  BookmarkStart,
  CommentRangeEnd,
  CommentRangeStart,
  CommentReference,
  DeletedTextRun,
  Document,
  ExternalHyperlink,
  InsertedTextRun,
  InternalHyperlink,
  PageBreak,
  Packer,
  Paragraph,
  Table,
  TableCell,
  TableRow,
  TextRun,
} from "docx";
import JSZip from "jszip";

const AUTHOR = "Kladde tests";

const meta = (title) => ({ creator: AUTHOR, lastModifiedBy: AUTHOR, title, description: "Generated by the Kladde e2e tests" });

/** Filler that makes a page tall enough to scroll: one short paragraph per entry. */
const filler = (n, label) => Array.from({ length: n }, (_, i) => new Paragraph({ children: [new TextRun(`${label} line ${i + 1}`)] }));

/**
 * A document of `pages` pages (explicit page breaks), each with a heading "Page N" and filler. The first page
 * has the marker text, an external link, an internal link and a table. `appPages` is the count in
 * `docProps/app.xml` (what Word writes on save; the package does not), null for none.
 */
export async function makeDocx({ pages = 5, marker = "Kladde viewer test document", links = [], appPages = pages } = {}) {
  const children = [];
  for (let page = 1; page <= pages; page++) {
    if (page > 1) children.push(new Paragraph({ children: [new PageBreak()] }));
    children.push(new Paragraph({ heading: "Heading1", children: [new TextRun(`Page ${page}`)] }));
    if (page === 1) {
      children.push(new Paragraph({ children: [new TextRun(marker)] }));
      for (const [text, link] of links) {
        children.push(new Paragraph({ children: [new ExternalHyperlink({ link, children: [new TextRun({ text, style: "Hyperlink" })] })] }));
      }
      children.push(
        new Paragraph({ children: [new InternalHyperlink({ anchor: "target-mark", children: [new TextRun("Jump to page 3")] })] }),
        new Table({
          rows: [
            new TableRow({ children: [new TableCell({ children: [new Paragraph("Cell A1")] }), new TableCell({ children: [new Paragraph("Cell B1")] })] }),
          ],
        }),
      );
    }
    if (page === 3) {
      children.push(new Paragraph({ children: [new BookmarkStart("target-mark", 1), new TextRun("Bookmark target"), new BookmarkEnd(1)] }));
    }
    children.push(...filler(12, `Page ${page}`));
  }
  const doc = new Document({ ...meta("Test document"), sections: [{ children }] });
  const bytes = Buffer.from(await Packer.toBuffer(doc));
  if (appPages == null) return bytes;
  const zip = await JSZip.loadAsync(bytes);
  zip.file(
    "docProps/app.xml",
    `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Properties xmlns="http://schemas.openxmlformats.org/officeDocument/2006/extended-properties"><Pages>${appPages}</Pages></Properties>`,
  );
  return Buffer.from(await zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE" }));
}

/** Tracked changes (an insertion by one author, a deletion by another) and a comment. */
export async function makeTrackedDocx() {
  const doc = new Document({
    ...meta("Tracked changes"),
    comments: { children: [{ id: 0, author: AUTHOR, date: new Date(0), children: [new Paragraph("Please check this price")] }] },
    sections: [
      {
        children: [
          new Paragraph({
            children: [
              new TextRun("The price is "),
              new DeletedTextRun({ text: "ninety", id: 1, author: "Reviewer One", date: "2020-01-01T00:00:00Z" }),
              new InsertedTextRun({ text: "one hundred", id: 2, author: "Reviewer Two", date: "2020-01-02T00:00:00Z" }),
              new TextRun(" euros."),
            ],
          }),
          new Paragraph({
            children: [new CommentRangeStart(0), new TextRun("Commented words"), new CommentRangeEnd(0), new TextRun({ children: [new CommentReference(0)] })],
          }),
        ],
      },
    ],
  });
  return Buffer.from(await Packer.toBuffer(doc));
}

/**
 * A document that tries everything: `remote` (https) and `plain` (http) are addresses on a local port that must
 * never be contacted, in an external image, a style (the font name is pasted into the generated CSS:
 * `Arial;background-image:url(...)`) and a VML shape's style, which the engine copies unchanged. The style also tries
 * to cover the whole window (`position: fixed`), as a shape can.
 *
 * `probes` are further https addresses, one per way in that does not look like an address to a scan for `url()`
 * (each should get its own listener, so the test can say which one got through): `fontVar` and `vmlVar` hide the
 * address in a custom property that `image-set(var(--x))` pastes in later, `fill` and `stroke` are VML colors the
 * engine copies into SVG attributes, `picture` is a linked VML picture. The font name of a second style also
 * closes the rule and adds a `:host` rule that tries to take the viewer's element over the window.
 */
export async function makeHostileDocx({ remote, plain = remote, probes = {} }) {
  const at = (name, path) => `${probes[name] ?? remote}/${path}`;
  const zip = await JSZip.loadAsync(await makeDocx({ pages: 1, marker: "Hostile document text" }));
  const cover = "position:fixed;top:0;left:0;width:100vw;height:100vh;z-index:99999;background-color:red";
  let styles = await zip.file("word/styles.xml").async("string");
  const injected = `<w:style w:type="character" w:customStyle="1" w:styleId="Evil"><w:name w:val="Evil"/><w:rPr><w:rFonts w:ascii="Arial;background-image:url(${remote}/style);${cover}" w:hAnsi="Arial"/></w:rPr></w:style>`;
  const hostBreakout = `Arial}:host{contain:none!important;position:fixed!important;inset:0!important;z-index:2147483647!important;background:red!important}.x{`;
  const injectedVar = `<w:style w:type="character" w:customStyle="1" w:styleId="EvilVar"><w:name w:val="EvilVar"/><w:rPr><w:rFonts w:ascii="Arial;--k:'${at("fontVar", "f.png")}';background-image:image-set(var(--k))" w:hAnsi="Arial"/></w:rPr></w:style>`;
  const injectedHost = `<w:style w:type="character" w:customStyle="1" w:styleId="EvilHost"><w:name w:val="EvilHost"/><w:rPr><w:rFonts w:ascii="${hostBreakout}" w:hAnsi="Arial"/></w:rPr></w:style>`;
  styles = styles.replace("</w:styles>", `${injected}${injectedVar}${injectedHost}</w:styles>`);
  zip.file("word/styles.xml", styles);

  let rels = await zip.file("word/_rels/document.xml.rels").async("string");
  rels = rels.replace("</Relationships>", `<Relationship Id="rIdEvil1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/image" Target="${remote}/linked.png" TargetMode="External"/><Relationship Id="rIdPicture" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/image" Target="${at("picture", "picture.png")}" TargetMode="External"/></Relationships>`);
  zip.file("word/_rels/document.xml.rels", rels);

  let body = await zip.file("word/document.xml").async("string");
  const evil = [
    `<w:p><w:r><w:rPr><w:rStyle w:val="Evil"/></w:rPr><w:t>Styled by the Evil style</w:t></w:r></w:p>`,
    `<w:p><w:r><w:rPr><w:rStyle w:val="EvilVar"/></w:rPr><w:t>Styled by the EvilVar style</w:t></w:r></w:p>`,
    `<w:p><w:r><w:rPr><w:rStyle w:val="EvilHost"/></w:rPr><w:t>Styled by the EvilHost style</w:t></w:r></w:p>`,
    `<w:p><w:r><w:pict><v:rect xmlns:v="urn:schemas-microsoft-com:vml" style="width:80pt;height:40pt;--v:&quot;${at("vmlVar", "v.png")}&quot;;background-image:image-set(var(--v) 1x)" fillcolor="red" stroked="f"/></w:pict></w:r></w:p>`,
    `<w:p><w:r><w:pict><v:rect xmlns:v="urn:schemas-microsoft-com:vml" style="width:80pt;height:40pt" fillcolor="url(${at("fill", "p.svg")}#g)" stroked="f"/></w:pict></w:r></w:p>`,
    `<w:p><w:r><w:pict><v:rect xmlns:v="urn:schemas-microsoft-com:vml" style="width:80pt;height:40pt" fillcolor="red"><v:stroke color="url(${at("stroke", "s.svg")}#g)"/></v:rect></w:pict></w:r></w:p>`,
    `<w:p><w:r><w:pict><v:shape xmlns:v="urn:schemas-microsoft-com:vml" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships" style="width:80pt;height:40pt"><v:imagedata r:id="rIdPicture"/></v:shape></w:pict></w:r></w:p>`,
    `<w:p><w:r><w:pict><v:rect xmlns:v="urn:schemas-microsoft-com:vml" style="width:80pt;height:40pt;background-image:url(${plain}/vml);${cover}" fillcolor="red" stroked="f"/></w:pict></w:r></w:p>`,
    `<w:p><w:r><w:drawing><wp:inline xmlns:wp="http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing" distT="0" distB="0" distL="0" distR="0"><wp:extent cx="952500" cy="952500"/><wp:docPr id="99" name="Linked"/><a:graphic xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main"><a:graphicData uri="http://schemas.openxmlformats.org/drawingml/2006/picture"><pic:pic xmlns:pic="http://schemas.openxmlformats.org/drawingml/2006/picture"><pic:nvPicPr><pic:cNvPr id="0" name="linked.png"/><pic:cNvPicPr/></pic:nvPicPr><pic:blipFill><a:blip xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships" r:link="rIdEvil1" r:embed="rIdEvil1"/></pic:blipFill><pic:spPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="952500" cy="952500"/></a:xfrm><a:prstGeom prst="rect"/></pic:spPr></pic:pic></a:graphicData></a:graphic></wp:inline></w:drawing></w:r></w:p>`,
  ].join("");
  // The section properties stay last in the body.
  const sect = body.match(/<w:sectPr[\s\S]*?<\/w:sectPr>/)?.[0] ?? "";
  body = body.replace(sect, "").replace("</w:body>", `${evil}${sect}</w:body>`);
  zip.file("word/document.xml", body);
  return Buffer.from(await zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE" }));
}

/**
 * A document that tries every way out it can: for the test that runs with the viewer's cleaning switched off, so
 * the frame's own policy is all that stands between the document and the network. `at(name)` is the address of
 * the listener of that way in (a failure then says which one got through).
 *
 * The renderer pastes font names into the generated CSS, so a name can carry declarations (`Arial;x:y`) or close
 * the rule and add whole rules and at-rules (`Arial}@font-face{...}.x{`): the CSS ways are those, one style each.
 * VML shapes copy `fillcolor` and the stroke color into SVG attributes and a linked picture becomes an SVG
 * `<image href>`; a linked drawing becomes an `<img src>`.
 */
export const ESCAPE_CSS_WAYS = {
  background: (at) => `Arial;background-image:url(${at("background")})`,
  imageSet: (at) => `Arial;background-image:image-set('${at("imageSet")}' 1x)`,
  imageSetVar: (at) => `Arial;--k:'${at("imageSetVar")}';background-image:image-set(var(--k))`,
  borderImage: (at) => `Arial;border-image-source:url(${at("borderImage")})`,
  listStyle: (at) => `Arial;display:list-item;list-style-image:url(${at("listStyle")})`,
  cursor: (at) => `Arial;cursor:url(${at("cursor")}),auto`,
  mask: (at) => `Arial;-webkit-mask-image:url(${at("mask")})`,
  filter: (at) => `Arial;filter:url(${at("filter")}#f)`,
  clipPath: (at) => `Arial;clip-path:url(${at("clipPath")}#c)`,
  shapeOutside: (at) => `Arial;float:left;shape-outside:url(${at("shapeOutside")})`,
  content: (at) => `Arial}p::before{content:url(${at("content")})}.x{`,
  // (An `@import` cannot be one of these: the engine's own rules come before it, so the browser ignores it. It is
  // tried as the first rule of a style of its own, see `ELEMENT_WAYS` in document.test.mjs.)
  fontFace: (at) => `Arial}@font-face{font-family:Probe;src:url(${at("fontFace")})}p{font-family:Probe}.x{`,
};

const xml = (text) => text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

export async function makeEscapeDocx({ at }) {
  const zip = await JSZip.loadAsync(await makeDocx({ pages: 1, marker: "Escape document text" }));
  const ways = Object.entries(ESCAPE_CSS_WAYS);
  const styleId = (name) => `Way${name[0].toUpperCase()}${name.slice(1)}`;
  const styles = ways
    .map(([name, way]) => `<w:style w:type="character" w:customStyle="1" w:styleId="${styleId(name)}"><w:name w:val="${styleId(name)}"/><w:rPr><w:rFonts w:ascii="${xml(way(at))}" w:hAnsi="Arial"/></w:rPr></w:style>`)
    .join("");
  zip.file("word/styles.xml", (await zip.file("word/styles.xml").async("string")).replace("</w:styles>", `${styles}</w:styles>`));

  let rels = await zip.file("word/_rels/document.xml.rels").async("string");
  const image = "http://schemas.openxmlformats.org/officeDocument/2006/relationships/image";
  rels = rels.replace(
    "</Relationships>",
    `<Relationship Id="rIdLinked" Type="${image}" Target="${xml(at("img"))}" TargetMode="External"/><Relationship Id="rIdPicture" Type="${image}" Target="${xml(at("svgImage"))}" TargetMode="External"/></Relationships>`,
  );
  zip.file("word/_rels/document.xml.rels", rels);

  const vml = 'xmlns:v="urn:schemas-microsoft-com:vml"';
  const paragraphs = [
    ...ways.map(([name]) => `<w:p><w:r><w:rPr><w:rStyle w:val="${styleId(name)}"/></w:rPr><w:t>Way ${name}</w:t></w:r></w:p>`),
    `<w:p><w:r><w:pict><v:rect ${vml} style="width:80pt;height:40pt" fillcolor="url(${xml(at("svgFill"))}#g)" stroked="f"/></w:pict></w:r></w:p>`,
    `<w:p><w:r><w:pict><v:rect ${vml} style="width:80pt;height:40pt" fillcolor="red"><v:stroke color="url(${xml(at("svgStroke"))}#g)"/></v:rect></w:pict></w:r></w:p>`,
    `<w:p><w:r><w:pict><v:rect ${vml} style="width:80pt;height:40pt;fill:url(${xml(at("svgStyleFill"))}#g)" fillcolor="red" stroked="f"/></w:pict></w:r></w:p>`,
    `<w:p><w:r><w:pict><v:shape ${vml} xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships" style="width:80pt;height:40pt"><v:imagedata r:id="rIdPicture"/></v:shape></w:pict></w:r></w:p>`,
    `<w:p><w:r><w:drawing><wp:inline xmlns:wp="http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing" distT="0" distB="0" distL="0" distR="0"><wp:extent cx="952500" cy="952500"/><wp:docPr id="99" name="Linked"/><a:graphic xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main"><a:graphicData uri="http://schemas.openxmlformats.org/drawingml/2006/picture"><pic:pic xmlns:pic="http://schemas.openxmlformats.org/drawingml/2006/picture"><pic:nvPicPr><pic:cNvPr id="0" name="linked.png"/><pic:cNvPicPr/></pic:nvPicPr><pic:blipFill><a:blip xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships" r:link="rIdLinked" r:embed="rIdLinked"/></pic:blipFill><pic:spPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="952500" cy="952500"/></a:xfrm><a:prstGeom prst="rect"/></pic:spPr></pic:pic></a:graphicData></a:graphic></wp:inline></w:drawing></w:r></w:p>`,
  ].join("");
  let body = await zip.file("word/document.xml").async("string");
  const sect = body.match(/<w:sectPr[\s\S]*?<\/w:sectPr>/)?.[0] ?? "";
  body = body.replace(sect, "").replace("</w:body>", `${paragraphs}${sect}</w:body>`);
  zip.file("word/document.xml", body);
  return Buffer.from(await zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE" }));
}

/** What Word saves for a password-protected or rights-managed file: an OLE compound file. */
export function makeEncryptedSignature() {
  const bytes = Buffer.alloc(4096);
  Buffer.from([0xd0, 0xcf, 0x11, 0xe0, 0xa1, 0xb1, 0x1a, 0xe1]).copy(bytes);
  return bytes;
}

/** A zip header followed by noise: starts like a document, is not one. */
export function makeCorrupt() {
  const bytes = Buffer.alloc(2048, 0x41);
  Buffer.from([0x50, 0x4b, 0x03, 0x04]).copy(bytes);
  return bytes;
}

/** The first `length` bytes of a document: what a reader sees while a program is still writing the file. */
export function truncate(bytes, length = Math.floor(bytes.length / 2)) {
  return bytes.subarray(0, length);
}
